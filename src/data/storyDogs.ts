export type StoryAnswers = Record<string, string[]>;
export const answerPlaceholder = "Use complete sentences. The more detail and examples you put in this box, the better your story outline will be.";
export const draftKey = "markcheverton:storydogs:v1";
export function missingStages(answers: StoryAnswers) {
  return storyDogs.filter(s => s.questions.some((_, i) => !answers[s.id]?.[i]?.trim()));
}
export function outlineText(answers: StoryAnswers) {
  return `${missingStages(answers).length ? "My StoryDogs Plot Outline (partial)" : "My StoryDogs Plot Outline"}\n\n` + storyDogs.map(s => `${s.label} — ${s.cue}\n${s.questions.map((q, i) => `${q}\n${answers[s.id]?.[i]?.trim() ? answers[s.id][i] : "[Not answered yet]"}`).join("\n\n")}`).join("\n\n");
}

